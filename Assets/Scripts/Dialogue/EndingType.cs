// EndingType.cs
public enum EndingType
{
    None,
    True,           // 트루엔딩: 내부 고발 및 아버지를 경찰에 넘김
    Normal,         // 노말엔딩: 증거 제출 후 신고
    Bad_A,          // 배드엔딩(사장복수): 사장을 칼로 찌르고 살인범이 됨
    Bad_B,          // 배드엔딩(차장복수): 조폭을 써서 차장 처리 후 새로운 사장이 됨
    Bad_C,          // 배드엔딩(수사 들킴): 도망치다 한성과 바다에 빠짐
    Bad_D,          // 배드엔딩(포기): 일상으로 복귀
    Bad_E,          // 배드엔딩(분노/콘크리트 실패)
    Bad_F,          // 배드엔딩(자료실 열쇠 미획득): #07에서 열쇠를 얻기 전에 조사를 그만둠
    Bad_G           // 배드엔딩(정체 발각): #07 회의실 사용 대장을 요구한 이유를 잘못 답해 사장에게 들킴
}
//현재 엔딩이 없어 임시로 None을 넣어둠. 나중에 엔딩이 생기면 True, Normal, Bad_A~E로 바꿔서 사용하면 됨.
